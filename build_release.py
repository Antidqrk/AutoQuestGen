def _source(relative: str) -> Path:
    path = REPO / relative
    if path.is_symlink() or not path.resolve().is_relative_to(REPO):
        raise ValueError(f"Runtime input must stay inside the checkout: {relative}")
    if not path.is_file():
        raise FileNotFoundError(f"Missing public runtime input: {relative}")
    return path


def runtime_files() -> list[tuple[str, str]]:
    """Return (source path, staged path) pairs for the public runtime only."""
    from decor_library import load_catalog
    pairs = [(name, name) for name in ROOT_SHIP]
    pairs += [(f"moddb/{name}", f"moddb/{name}") for name in MODDB_SHIP]
    for folder in ("chains_research", "guides"):
        paths = sorted((REPO / "moddb" / folder).rglob("*.json"))
        if not paths:
            raise ValueError(f"Missing public progression data: moddb/{folder}")
        pairs += [(p.relative_to(REPO).as_posix(), p.relative_to(REPO).as_posix()) for p in paths]
    catalog = load_catalog(REPO / "decor_assets")
    if len(catalog.assets) < 51:
        raise ValueError("Expected the complete bundled artwork catalog")
    for name in list(ART_METADATA) + [asset.path for asset in catalog.assets]:
        relative = "decor_assets/" + name
        pairs.append((relative, relative))
    pairs.append(("README.md", "README.md"))
    license_name = "LICENSE" if (REPO / "LICENSE").is_file() else "LICENSE.txt"
    pairs.append((license_name, "LICENSE.txt"))
    for source, _destination in pairs:
        _source(source)
    return pairs


def _has_quote_key(value: object) -> bool:
    if isinstance(value, dict):
        return "quote" in value or any(_has_quote_key(v) for v in value.values())
    if isinstance(value, list):
        return any(_has_quote_key(v) for v in value)
    return False


def verify_stage() -> None:
    """Reject unexpected files and unsanitized narration; validate images."""
    from decor_library import load_catalog
    expected = {destination for _source_name, destination in runtime_files()}
    generated = {"AutoQuestGen_onefile.spec", "version_info.txt"}
    actual = {p.relative_to(STAGE).as_posix() for p in STAGE.rglob("*") if p.is_file()}
    missing, extra = expected - actual, actual - expected - generated
    if missing or extra:
        raise ValueError(f"Staging mismatch; missing={sorted(missing)}, extra={sorted(extra)}")
    for path in (STAGE / "moddb" / "guides").glob("*.json"):
        if _has_quote_key(json.loads(path.read_text(encoding="utf-8"))):
            raise ValueError(f"Unsanitized narration in {path.name}")
    load_catalog(STAGE / "decor_assets")
    print(f"Public stage verified: {len(expected)} runtime files")


def stage() -> list[dict]:
    pairs = runtime_files()  # Validate before replacing the previous stage.
    intended = REPO / "build" / "stage"
    if STAGE.is_symlink() or STAGE.resolve() != intended:
        raise ValueError("Refusing to replace staging outside this checkout")
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    manifest = []
    for source, destination in pairs:
        output = STAGE / destination
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(_source(source), output)
        data = output.read_bytes()
        manifest.append({"path": destination, "bytes": len(data),
                         "sha256": hashlib.sha256(data).hexdigest()})
    verify_stage()
    (REPO / "build" / "manifest.json").write_text(
        json.dumps({"files": manifest}, indent=2) + "\n", encoding="utf-8")
    return manifest


def build() -> None:
    if sys.platform != "win32":
        raise RuntimeError("Build the Windows executable on Windows; --stage works separately")
    (STAGE / "AutoQuestGen_onefile.spec").write_text(SPEC, encoding="utf-8")
    (STAGE / "version_info.txt").write_text(VERSION_INFO.format(
        version=repr(RELEASE), dotted=".".join(map(str, RELEASE))), encoding="utf-8")
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(DIST), "--workpath", str(REPO / "build" / "pyinstaller"),
                    "AutoQuestGen_onefile.spec"], cwd=STAGE, check=True)
    executable = DIST / "AutoQuestGen.exe"
    if not executable.is_file():
        raise RuntimeError("PyInstaller did not produce AutoQuestGen.exe")
    for name in ("README.md", "LICENSE.txt"):
        shutil.copy2(STAGE / name, DIST / name)
    digest = hashlib.sha256(executable.read_bytes()).hexdigest()
    print(f"Local build: {executable.name}, {executable.stat().st_size} bytes, SHA256 {digest}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", action="store_true", help="validate inputs without freezing")
    args = parser.parse_args()
    stage()
    if not args.stage:
        build()


if __name__ == "__main__":
    main()
